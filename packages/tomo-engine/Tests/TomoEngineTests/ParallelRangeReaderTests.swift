import Foundation
import XCTest

@testable import TomoEngine

/// The parallel ranged reader against a real local HTTP server: in-order bytes,
/// seeks, and the refusal that keeps range-less servers on the plain path.
final class ParallelRangeReaderTests: XCTestCase {
    private static let serverScript = """
    const http = require("http"), fs = require("fs");
    const file = process.argv[1], mode = process.argv[2], ranges = mode !== "plain", freezeAt = Number(process.argv[3] || 0);
    const size = fs.statSync(file).size;
    // Bodies being sent at once, and the most there ever were: what a provider's connection cap counts.
    let active = 0, peak = 0, requests = 0, frozen = 0, single = 0;
    const server = http.createServer((req, res) => {
      if (req.url === "/stats") return res.end(JSON.stringify({ active, peak, requests, frozen, single }));
      // "hang" accepts the request and never answers it.
      if (mode === "hang") return;
      const m = ranges && /^bytes=(\\d+)-(\\d+)?$/.exec(req.headers.range || "");
      // Keep the ordinary FFmpeg retry pending, so a test can inspect the failed ranged read's close.
      if (mode === "invalid" && (!m || !m[2])) { single++; return; }
      if (m) {
        const start = Number(m[1]), end = m[2] ? Number(m[2]) : size - 1;
        if (end > start) requests++;
        if (mode === "refuse" && end > start) { res.writeHead(403); return res.end("provider connection limit"); }
        // "cap" is a provider allowing one connection: a body asked for beside another is refused.
        if (mode === "cap" && end > start && active >= 1) { res.writeHead(403); return res.end(); }
        res.writeHead(206, { "Content-Range": `bytes ${start}-${end}/${size}`, "Content-Length": end - start + 1 });
        // "stall" answers the one-byte probe and then sends headers with no body.
        if (mode === "stall" && end > start) return res.flushHeaders();
        // "freeze" sends the first bytes of the chunk at freezeAt once, then nothing, the connection left open.
        if (mode === "freeze" && start === freezeAt && frozen === 0) {
          frozen++;
          const fd = fs.openSync(file, "r"), head = Buffer.alloc(65536);
          fs.readSync(fd, head, 0, 65536, start);
          fs.closeSync(fd);
          return res.write(head);
        }
        // "trickle" sends every body 64 KB each 100 ms: slow, never silent.
        if (mode === "trickle" && end > start) {
          const fd = fs.openSync(file, "r");
          let pos = start;
          const step = () => {
            const len = Math.min(65536, end - pos + 1), buf = Buffer.alloc(len);
            fs.readSync(fd, buf, 0, len, pos);
            res.write(buf);
            pos += len;
            if (pos > end) { fs.closeSync(fd); res.end(); } else setTimeout(step, 100);
          };
          return step();
        }
        // "?hold" is a read that never finishes: it keeps its connection until the client lets go.
        if (req.url.includes("hold")) {
          peak = Math.max(peak, ++active);
          res.on("close", () => active--);
          return res.flushHeaders();
        }
        if (end > start) {
          peak = Math.max(peak, ++active);
          res.on("close", () => active--);
        }
        // "slow" holds every body back, so the requests a reader keeps in flight pile up.
        const send = () => fs.createReadStream(file, { start, end }).pipe(res);
        if (mode === "slow" && end > start) setTimeout(send, 250); else send();
      } else {
        res.writeHead(200, { "Content-Length": size });
        fs.createReadStream(file).pipe(res);
      }
    });
    server.listen(0, "127.0.0.1", () => console.log(server.address().port));
    """

    private var server: Process?
    private var fileURL: URL!
    private var payload: Data!
    private var port = 0

    /// Serves generated bytes, or `media` when a test needs a file the demuxer can open.
    private func startServer(ranges: Bool, bytes: Int = 9_000_000, mode: String? = nil, media: URL? = nil, freezeAt: Int = 0) throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("prr-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        addTeardownBlock { try? FileManager.default.removeItem(at: dir) }
        fileURL = dir.appendingPathComponent("payload.bin")
        if let media {
            payload = try Data(contentsOf: media)
        } else {
            var data = Data(count: bytes)
            data.withUnsafeMutableBytes { raw in
                var state: UInt64 = 0x9E37_79B9_7F4A_7C15
                for i in 0 ..< raw.count {
                    state = state &* 6_364_136_223_846_793_005 &+ 1_442_695_040_888_963_407
                    raw[i] = UInt8(truncatingIfNeeded: state >> 33)
                }
            }
            payload = data
        }
        try payload.write(to: fileURL)

        let node = ["/opt/homebrew/bin/node", "/usr/local/bin/node"].first { FileManager.default.isExecutableFile(atPath: $0) }
        guard let node else { throw XCTSkip("no node on this host") }
        let process = Process()
        process.executableURL = URL(fileURLWithPath: node)
        process.arguments = ["-e", Self.serverScript, fileURL.path, mode ?? (ranges ? "ranges" : "plain"), String(freezeAt)]
        let pipe = Pipe()
        process.standardOutput = pipe
        try process.run()
        server = process
        addTeardownBlock { [weak process] in process?.terminate() }
        guard let line = pipe.fileHandleForReading.availableData.split(separator: UInt8(ascii: "\n")).first,
              let parsed = Int(String(decoding: line, as: UTF8.self)) else {
            throw XCTSkip("server did not report a port")
        }
        port = parsed
    }

    private func url() -> URL { URL(string: "http://127.0.0.1:\(port)/payload.bin")! }

    private func serverStat(_ name: String) throws -> Int {
        let data = try Data(contentsOf: URL(string: "http://127.0.0.1:\(port)/stats")!)
        return try XCTUnwrap((JSONSerialization.jsonObject(with: data) as? [String: Int])?[name])
    }

    /// The most ranged bodies the server ever sent at once.
    private func peakConnections() throws -> Int { try serverStat("peak") }

    /// A provider that allows one connection and has told nobody: a lower read holds it when the film
    /// opens. The refusal teaches the limit, the lower read yields, and the film reads on the one connection.
    func testAFileRefusedByItsProviderLearnsTheLimitAndTakesTheLowerReadsConnection() throws {
        let film = try film()
        try startServer(ranges: true, mode: "cap", media: film)
        let key = "learn-\(UUID().uuidString)"
        defer { LiveConnectionBroker.shared.setBudget(0, for: key) }

        var request = URLRequest(url: URL(string: "http://127.0.0.1:\(port)/payload.bin?hold=1")!)
        request.setValue("bytes=0-1000", forHTTPHeaderField: "Range")
        let holder = URLSession(configuration: .ephemeral).dataTask(with: request)
        var held: LiveConnectionBroker.Lease?
        held = try XCTUnwrap(LiveConnectionBroker.shared.tryAcquire(key: key, priority: .sweep, onRevoke: {
            holder.cancel()
            held?.release()
        }))
        holder.resume()
        let holding = XCTNSPredicateExpectation(predicate: NSPredicate { _, _ in (try? self.serverStat("active")) == 1 }, object: nil)
        wait(for: [holding], timeout: 5)

        var config = makeConfig(durationSeconds: 13, inputUrl: url().absoluteString, width: 640, height: 360, frameRate: 25, readAheadSegments: 8)
        config.liveOriginKey = key
        let session = try RemuxSession(config: config)
        var failure: String?
        session.onFailed = { failure = $0["message"] as? String }
        session.start()
        defer { session.stop() }
        let opened = Date()
        _ = session.masterPlaylist()
        let segment = session.segmentURL(1)
        print("[refusal] master and segment 1 after \(Date().timeIntervalSince(opened))s")

        XCTAssertNil(failure)
        XCTAssertNotNil(segment)
        XCTAssertEqual(LiveConnectionBroker.shared.budget(for: key), 1)
        XCTAssertEqual(LiveConnectionBroker.shared.activeCount(for: key), 1)
        XCTAssertEqual(try peakConnections(), 1)
    }

    private func drain(_ reader: ParallelRangeReader) {
        let buffer = UnsafeMutableRawPointer.allocate(byteCount: 65536, alignment: 1)
        defer { buffer.deallocate() }
        while reader.read(into: buffer, count: 65536) > 0 {}
    }

    func testAProbeAndRefusedChunkBodiesDoNotCountAsAServedRead() throws {
        try startServer(ranges: true, mode: "refuse")
        let reader = try XCTUnwrap(ParallelRangeReader.open(url: url(), headers: [:]))
        drain(reader)
        reader.close()
        XCTAssertGreaterThanOrEqual(try serverStat("requests"), 1)
        XCTAssertFalse(reader.servedBody)
    }

    func testARangedBodyRejectedByTheDemuxerStillCountsAsARecentClose() throws {
        // Random bytes have a successful HTTP response but no media format.
        try startServer(ranges: true, bytes: 3 * ParallelRangeReader.chunkBytes, mode: "invalid")
        let key = "invalid-\(UUID().uuidString)"
        var config = makeConfig(durationSeconds: 13, inputUrl: url().absoluteString, width: 640, height: 360, frameRate: 25)
        config.liveOriginKey = key
        config.inputConnections = 3
        let session = try RemuxSession(config: config)
        session.start()
        defer { session.stop() }
        let retrying = XCTNSPredicateExpectation(predicate: NSPredicate { _, _ in (try? self.serverStat("single")) == 1 }, object: nil)
        wait(for: [retrying], timeout: 10)

        XCTAssertFalse(session.hasFailed)
        XCTAssertEqual(LiveConnectionBroker.shared.activeCount(for: key), 1, "the surplus reservations must have returned")
        XCTAssertTrue(LiveConnectionBroker.shared.recentlyClosed(key: key, within: 15), "a served body still counts even when it is not media")
        XCTAssertNil(LiveConnectionBroker.shared.budget(for: key))
    }

    /// One connection means one request in flight, however far the window reaches.
    func testAReaderGivenOneConnectionKeepsOneRequestInFlight() throws {
        try startServer(ranges: true, mode: "slow")
        let reader = try XCTUnwrap(ParallelRangeReader.open(url: url(), headers: [:], connections: 1))
        defer { reader.close() }
        drain(reader)
        XCTAssertEqual(reader.connections, 1)
        XCTAssertEqual(try peakConnections(), 1)
    }

    /// A count past the default is honoured: the window widens so every connection has a chunk to fetch.
    func testAReaderGivenSixConnectionsUsesAllSix() throws {
        try startServer(ranges: true, bytes: 16 * ParallelRangeReader.chunkBytes, mode: "slow")
        let reader = try XCTUnwrap(ParallelRangeReader.open(url: url(), headers: [:], connections: 6))
        defer { reader.close() }
        drain(reader)
        XCTAssertEqual(reader.connections, 6)
        XCTAssertEqual(try peakConnections(), 6)
    }

    func testAnUnnamedCountIsTheDefaultAndAnAbsurdOneIsBounded() throws {
        try startServer(ranges: true)
        let unnamed = try XCTUnwrap(ParallelRangeReader.open(url: url(), headers: [:]))
        defer { unnamed.close() }
        XCTAssertEqual(unnamed.connections, ParallelRangeReader.defaultConnections)
        let absurd = try XCTUnwrap(ParallelRangeReader.open(url: url(), headers: [:], connections: 500))
        defer { absurd.close() }
        XCTAssertEqual(absurd.connections, ParallelRangeReader.maxConnections)
    }

    /// A film over HTTP, big enough for a reader (more than one chunk).
    private func film() throws -> URL {
        let ffmpeg = ["/Applications/Jellyfin.app/Contents/MacOS/ffmpeg", "/opt/homebrew/bin/ffmpeg"].first { FileManager.default.isExecutableFile(atPath: $0) }
        guard let ffmpeg else { throw XCTSkip("no ffmpeg on this host") }
        let dir = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent(".build/ranged-fixtures", isDirectory: true)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        let out = dir.appendingPathComponent("noise-13s.mkv")
        if FileManager.default.fileExists(atPath: out.path) { return out }
        let process = Process()
        process.executableURL = URL(fileURLWithPath: ffmpeg)
        // Noise does not compress: 13 s at this rate is several chunks.
        process.arguments = ["-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", "testsrc2=size=640x360:rate=25:duration=13",
                             "-f", "lavfi", "-i", "sine=frequency=440:duration=13:sample_rate=48000",
                             "-vf", "noise=alls=60:allf=t", "-c:v", "libx264", "-b:v", "6M", "-minrate", "6M", "-maxrate", "6M", "-bufsize", "6M",
                             "-pix_fmt", "yuv420p", "-g", "25", "-c:a", "aac", out.path]
        process.standardOutput = FileHandle.nullDevice
        process.standardError = FileHandle.nullDevice
        try process.run()
        process.waitUntilExit()
        guard process.terminationStatus == 0, FileManager.default.fileExists(atPath: out.path) else {
            try? FileManager.default.removeItem(at: out)
            throw XCTSkip("ffmpeg could not generate the film")
        }
        return out
    }

    /// A session asking for three connections on a provider that allows two reads over two, holding a lease for each.
    func testAFileOpensAsManyConnectionsAsItsProviderSpares() throws {
        let film = try film()
        try XCTSkipUnless((try film.resourceValues(forKeys: [.fileSizeKey]).fileSize ?? 0) > 2 * ParallelRangeReader.chunkBytes, "the film is too small for a reader")
        try startServer(ranges: true, mode: "slow", media: film)
        let key = "ranged-\(UUID().uuidString)"
        LiveConnectionBroker.shared.setBudget(2, for: key)
        defer { LiveConnectionBroker.shared.setBudget(0, for: key) }
        var config = makeConfig(durationSeconds: 13, inputUrl: url().absoluteString, width: 640, height: 360, frameRate: 25, readAheadSegments: 8)
        config.liveOriginKey = key
        config.inputConnections = 3
        let session = try RemuxSession(config: config)
        session.start()
        _ = session.masterPlaylist()
        _ = session.segmentURL(1)

        XCTAssertFalse(session.hasFailed)
        XCTAssertEqual(LiveConnectionBroker.shared.activeCount(for: key), 2)
        XCTAssertEqual(try peakConnections(), 2)

        session.stop()
        let released = session.waitUntil(deadline: 10) { LiveConnectionBroker.shared.activeCount(for: key) == 0 }
        XCTAssertTrue(released, "a lease outlived the session")
    }

    /// The same session on a provider that allows one reads on one connection, with no reader.
    func testAFileOnAOneConnectionProviderReadsOnOne() throws {
